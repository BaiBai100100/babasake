export const GAMES = {
  yamanote: { name: '山手線ゲーム', make: (r) => pick(r, YAMANOTE) },
  banana: { name: 'マジカルバナナ', make: (r) => pick(r, BANANA) },
  // どすこい：頭文字と文字数の両方をアプリが決める
  dosukoi: { name: 'どすこいゲーム', make: (r) => `『${pick(r, DOSUKOI)}』で始まる${pick(r, DOSUKOI_LEN)}文字の言葉` },
  // どすこい3本勝負：頭文字（3つともちがう文字）と文字数を3回ぶん決める
  dosukoi3: {
    name: 'どすこいゲーム3本勝負',
    make: (r) => {
      const left = [...DOSUKOI];
      const out = [];
      for (let i = 0; i < 3; i++) out.push(`『${left.splice(Math.floor(r() * left.length) % left.length, 1)[0]}』${pick(r, DOSUKOI_LEN)}文字`);
      return out.join('→');
    },
  },
  atama: {
    name: 'あたまおしりゲーム',
    make: (r) => {
      const w = pick(r, ATAMA_WORDS);
      return `「${w[0]}」で始まって「${w[w.length - 1]}」で終わる`;
    },
  },
  moji: {
    name: '文字数しばりしりとり',
    make: (r) => `${3 + Math.floor(r() * 3)}文字の言葉だけ・最初は「${pick(r, MOJI_START)}」`,
  },
  majority: {
    name: '多数決ゲーム',
    make: (r) => {
      const [a, b] = pick(r, MAJORITY);
      return `「${a}」か「${b}」か`;
    },
  },
  inshou: { name: '第一印象ゲーム', make: (r) => pick(r, INSHOU) },
  mozza: { name: 'モッツァレラチーズゲーム', make: (r) => pick(r, MOZZA) },
};

// カードを引いた（選んだ）瞬間にお題を決める
export function makeTopic(game, rng = Math.random) {
  const def = GAMES[game];
  return def ? { game, text: def.make(rng) } : null;
}

// 文面の {お題} を置き換える（お題が決まる前は「？？？」）
export const fillTopic = (t, topic) => t.replaceAll('{お題}', topic?.text ?? '？？？');
